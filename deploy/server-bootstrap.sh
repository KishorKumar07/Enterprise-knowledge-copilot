#!/usr/bin/env bash
# One-time (and safe to re-run) setup of the EC2 app server for the Enterprise
# Knowledge Copilot. Run it ON the server, as root:
#
#   sudo bash server-bootstrap.sh
#
# It does NOT touch System Design Studio (/opt/apps/sds, its own Nginx file and
# its own containers). It creates:
#   /opt/apps/ekc/repo     git checkout of this (public) repo
#   /opt/apps/ekc/.env     secrets, chmod 600 -- generated here, never in git or GitHub
#   /etc/nginx/conf.d/ekc.conf        site config (HTTP only; certbot adds HTTPS later)
#   /etc/nginx/.htpasswd-ekc          basic-auth login for the Phoenix traces page
#
# Re-running never overwrites an existing .env or password file.
#
# For tests, paths and prompts can be overridden with environment variables
# (EKC_APP_DIR, EKC_NGINX_CONF_DIR, EKC_NGINX_DIR, EKC_REPO_URL, EKC_NONINTERACTIVE,
# EKC_GEMINI_API_KEY, EKC_GROQ_API_KEY, ...). On the real server none are needed.
set -euo pipefail

HOSTNAME_PUBLIC="${EKC_HOSTNAME:-kishor-ekc.duckdns.org}"
PUBLIC_URL="https://${HOSTNAME_PUBLIC}"
APP_DIR="${EKC_APP_DIR:-/opt/apps/ekc}"
REPO_URL="${EKC_REPO_URL:-https://github.com/KishorKumar07/Enterprise-knowledge-copilot.git}"
NGINX_CONF_DIR="${EKC_NGINX_CONF_DIR:-/etc/nginx/conf.d}"
NGINX_DIR="${EKC_NGINX_DIR:-/etc/nginx}"
NONINTERACTIVE="${EKC_NONINTERACTIVE:-}"

say()  { printf '\n\033[1m== %s ==\033[0m\n' "$*"; }
warn() { printf '\033[33m!! %s\033[0m\n' "$*" >&2; }
rand() { python3 -c "import secrets;print(secrets.token_urlsafe(${1:-24}))"; }

[ "$(id -u)" -eq 0 ] || { echo "run as root: sudo bash $0" >&2; exit 1; }

# Ask for a value unless it is already in the environment. $3=secret hides typing.
ask() {
  local var="$1" prompt="$2" secret="${3:-}" env_name="EKC_$1" value=""
  value="${!env_name:-}"
  if [ -z "$value" ] && [ -z "$NONINTERACTIVE" ]; then
    if [ -n "$secret" ]; then read -r -s -p "$prompt: " value </dev/tty; echo; else read -r -p "$prompt: " value </dev/tty; fi
  fi
  printf -v "$var" '%s' "$value"
}

say "1/6 Server health check"
df -h / | tail -1
awk '/MemTotal/{t=$2} /MemAvailable/{a=$2} END{printf "RAM: %d MB total, %d MB available\n", t/1024, a/1024}' /proc/meminfo
avail_gb="$(df -BG --output=avail / | tail -1 | tr -dc '0-9')"
if [ "${avail_gb:-0}" -lt 8 ]; then
  warn "Only ${avail_gb} GB free on /. The backend image is ~2 GB; free space first:  docker image prune -a"
fi
for tool in git docker python3; do
  command -v "$tool" >/dev/null || { echo "missing required tool: $tool" >&2; exit 1; }
done

say "2/6 Code checkout"
mkdir -p "$APP_DIR"
if [ -d "$APP_DIR/repo/.git" ]; then
  echo "repo already present"
else
  git clone --depth 1 "$REPO_URL" "$APP_DIR/repo"
fi

say "3/6 Secrets file"
if [ -f "$APP_DIR/.env" ]; then
  echo "$APP_DIR/.env already exists - leaving it alone"
else
  echo "Paste values when asked (typing is hidden). Press Enter to skip optional ones."
  ask GEMINI_API_KEY "Gemini API key" secret
  ask GROQ_API_KEY "Groq API key (fallback)" secret
  ask GOOGLE_CLIENT_ID "Google OAuth client id (optional)"
  ask GOOGLE_CLIENT_SECRET "Google OAuth client secret (optional)" secret
  ask SLACK_CLIENT_ID "Slack client id (optional)"
  ask SLACK_CLIENT_SECRET "Slack client secret (optional)" secret

  if [ -z "$GEMINI_API_KEY" ] && [ -z "$GROQ_API_KEY" ]; then
    warn "No Gemini or Groq key given: the site will run but chat cannot answer until one is added to $APP_DIR/.env"
  fi

  GRAFANA_PASSWORD="$(rand 18)"
  umask 077
  cat > "$APP_DIR/.env" <<ENVFILE
# Production secrets for the Enterprise Knowledge Copilot. chmod 600. Never commit.
# Generated by deploy/server-bootstrap.sh on $(date -u +%FT%TZ)
ENVIRONMENT=production
PUBLIC_URL=${PUBLIC_URL}
FRONTEND_ORIGIN=${PUBLIC_URL}

# Database (compose builds DATABASE_URL from this)
POSTGRES_PASSWORD=$(rand 24)

# Auth. Changing CREDENTIAL_ENCRYPTION_KEY later makes every stored OAuth token unreadable.
JWT_SECRET=$(rand 32)
JWT_ALGORITHM=HS256
JWT_EXPIRE_MINUTES=10080
SESSION_COOKIE_NAME=ekc_session
COOKIE_SECURE=true
COOKIE_SAMESITE=lax
CREDENTIAL_ENCRYPTION_KEY=$(python3 -c "import os,base64;print(base64.urlsafe_b64encode(os.urandom(32)).decode())")

# Chat LLMs (remote APIs)
GEMINI_API_KEY=${GEMINI_API_KEY}
GEMINI_MODEL=gemini-flash-latest
GEMINI_UTILITY_MODEL=gemini-flash-lite-latest
GROQ_API_KEY=${GROQ_API_KEY}
GROQ_MODEL=openai/gpt-oss-120b
GROQ_UTILITY_MODEL=allam-2-7b

# Source connectors (redirect URIs must also be registered in the Google / Slack consoles)
GOOGLE_CLIENT_ID=${GOOGLE_CLIENT_ID}
GOOGLE_CLIENT_SECRET=${GOOGLE_CLIENT_SECRET}
GOOGLE_REDIRECT_URI=${PUBLIC_URL}/api/sources/google-drive/callback
SLACK_CLIENT_ID=${SLACK_CLIENT_ID}
SLACK_CLIENT_SECRET=${SLACK_CLIENT_SECRET}
SLACK_REDIRECT_URI=${PUBLIC_URL}/api/sources/slack/callback

# Observability
OTEL_ENABLED=true
GF_SECURITY_ADMIN_USER=admin
GF_SECURITY_ADMIN_PASSWORD=${GRAFANA_PASSWORD}
ENVFILE
  chmod 600 "$APP_DIR/.env"
  echo ".env written (chmod 600)."
  echo
  echo "  Grafana login (save this):  admin / ${GRAFANA_PASSWORD}"
  echo "  It is also stored in $APP_DIR/.env as GF_SECURITY_ADMIN_PASSWORD."
fi

say "4/6 Phoenix login (Nginx basic auth)"
if [ -f "$NGINX_DIR/.htpasswd-ekc" ]; then
  echo "$NGINX_DIR/.htpasswd-ekc already exists - leaving it alone"
else
  PHOENIX_PASSWORD="$(rand 14)"
  if command -v htpasswd >/dev/null; then
    htpasswd -bc "$NGINX_DIR/.htpasswd-ekc" admin "$PHOENIX_PASSWORD" >/dev/null
  else
    # No apache tools needed: write an APR1 hash with openssl.
    printf 'admin:%s\n' "$(openssl passwd -apr1 "$PHOENIX_PASSWORD")" > "$NGINX_DIR/.htpasswd-ekc"
  fi
  chmod 640 "$NGINX_DIR/.htpasswd-ekc"
  chgrp nginx "$NGINX_DIR/.htpasswd-ekc" 2>/dev/null || true
  echo "  Phoenix login (save this):  admin / ${PHOENIX_PASSWORD}"
fi

say "5/6 Nginx site"
mkdir -p "$NGINX_CONF_DIR"
cp "$APP_DIR/repo/deploy/nginx-ekc.conf" "$NGINX_CONF_DIR/ekc.conf"
if command -v nginx >/dev/null; then
  nginx -t
  if [ -z "${EKC_SKIP_NGINX_RELOAD:-}" ]; then systemctl reload nginx; fi
else
  warn "nginx not installed here; config copied but not tested"
fi

say "6/6 Done"
cat <<NEXT

Server is prepared. Still to do (from your side):
  1. DuckDNS: ${HOSTNAME_PUBLIC} must point at this server's Elastic IP.
  2. Then get the HTTPS certificate:   sudo certbot --nginx -d ${HOSTNAME_PUBLIC}
  3. In GitHub, set the repository variable DEPLOY_ENABLED=true and re-run Deploy.
NEXT
